"""Atomic, private local filesystem blob store.

Storage keys are generated by this module and are deliberately opaque. User
filenames are display metadata only and never participate in path resolution.
"""

from __future__ import annotations

import hashlib
import logging
import os
import re
import secrets
import tempfile
from collections.abc import Iterator
from contextlib import contextmanager
from pathlib import Path
from typing import BinaryIO

from rag_eval_api.storage.errors import (
    BlobAlreadyExists,
    BlobChecksumMismatch,
    BlobKeyError,
    BlobNotFound,
    BlobSecurityError,
    BlobSizeExceeded,
)
from rag_eval_api.storage.protocol import StoredBlob

LOGGER = logging.getLogger(__name__)
_KEY_PATTERN = re.compile(r"^[a-z2-7]{16}/[a-z2-7]{32}$")
_READ_CHUNK_SIZE = 1024 * 1024


class LocalBlobStore:
    """A private local backend with no overwrite and atomic publication."""

    def __init__(self, root: str | Path, *, max_bytes: int = 50 * 1024 * 1024) -> None:
        if max_bytes < 1:
            raise ValueError("max_bytes must be positive")
        self.root = Path(root)
        if not self.root.is_absolute():
            raise BlobSecurityError("blob root must be absolute")
        if self.root.exists() and self.root.is_symlink():
            raise BlobSecurityError("blob root must not be a symlink")
        self.root.mkdir(mode=0o700, parents=True, exist_ok=True)
        self.root.chmod(0o700)
        self.max_bytes = max_bytes

    def put(
        self,
        source: BinaryIO,
        *,
        expected_sha256: str | None = None,
        max_bytes: int | None = None,
    ) -> StoredBlob:
        limit = self.max_bytes if max_bytes is None else min(max_bytes, self.max_bytes)
        if limit < 1:
            raise ValueError("max_bytes must be positive")
        temp_path: Path | None = None
        try:
            temp_path = self._write_temp(source, limit=limit)
            byte_size, sha256 = self._digest_file(temp_path)
            if expected_sha256 is not None and sha256 != expected_sha256:
                raise BlobChecksumMismatch("blob checksum does not match the declared digest")
            key = self._new_key()
            destination = self._path_for_key(key)
            self._publish_temp_file(temp_path, destination)
            temp_path = None
            LOGGER.info("blob stored", extra={"blob_size": byte_size, "blob_sha256": sha256})
            return StoredBlob(storage_key=key, byte_size=byte_size, sha256=sha256)
        finally:
            if temp_path is not None:
                self._unlink_quietly(temp_path)

    def _write_temp(self, source: BinaryIO, *, limit: int | None = None) -> Path:
        effective_limit = self.max_bytes if limit is None else limit
        fd, raw_path = tempfile.mkstemp(prefix=".upload-", dir=self.root, text=False)
        temp_path = Path(raw_path)
        os.fchmod(fd, 0o600)
        try:
            with os.fdopen(fd, "wb") as destination:
                total = 0
                while True:
                    chunk = source.read(_READ_CHUNK_SIZE)
                    if not chunk:
                        break
                    if not isinstance(chunk, bytes):
                        raise TypeError("blob source must return bytes")
                    total += len(chunk)
                    if total > effective_limit:
                        raise BlobSizeExceeded("blob exceeds the configured size limit")
                    destination.write(chunk)
                destination.flush()
                os.fsync(destination.fileno())
        except BaseException:
            self._unlink_quietly(temp_path)
            raise
        return temp_path

    @staticmethod
    def _digest_file(path: Path) -> tuple[int, str]:
        digest = hashlib.sha256()
        size = 0
        with path.open("rb") as source:
            while chunk := source.read(_READ_CHUNK_SIZE):
                size += len(chunk)
                digest.update(chunk)
        return size, digest.hexdigest()

    def _new_key(self) -> str:
        # 240 bits of entropy; the first component also spreads files across directories.
        token = secrets.token_bytes(30)
        encoded = _base32(token)
        return f"{encoded[:16]}/{encoded[16:48]}"

    def _path_for_key(self, storage_key: str, *, create_parent: bool = True) -> Path:
        if not isinstance(storage_key, str) or not _KEY_PATTERN.fullmatch(storage_key):
            raise BlobKeyError("storage key is not a valid opaque key")
        first, second = storage_key.split("/", 1)
        directory = self.root / first
        if directory.exists() and directory.is_symlink():
            raise BlobKeyError("storage key resolves through a symlink")
        if create_parent:
            directory.mkdir(mode=0o700, exist_ok=True)
            directory.chmod(0o700)
        destination = directory / second
        if destination.is_symlink():
            raise BlobKeyError("storage key resolves to a symlink")
        return destination

    def _publish_temp_file(self, temp_path: Path, destination: Path) -> None:
        try:
            os.link(temp_path, destination, follow_symlinks=False)
        except FileExistsError as exc:
            raise BlobAlreadyExists("blob storage key already exists") from exc
        except OSError as exc:
            raise BlobSecurityError("blob could not be published safely") from exc
        finally:
            self._unlink_quietly(temp_path)

    @contextmanager
    def open(self, storage_key: str) -> Iterator[BinaryIO]:
        path = self._path_for_key(storage_key, create_parent=False)
        flags = os.O_RDONLY | getattr(os, "O_NOFOLLOW", 0)
        try:
            fd = os.open(path, flags)
        except FileNotFoundError as exc:
            raise BlobNotFound("blob does not exist") from exc
        except OSError as exc:
            raise BlobSecurityError("blob could not be opened safely") from exc
        try:
            with os.fdopen(fd, "rb") as handle:
                yield handle
        finally:
            # fdopen owns the descriptor; this is intentionally a no-op for clarity.
            pass

    def exists(self, storage_key: str) -> bool:
        path = self._path_for_key(storage_key, create_parent=False)
        try:
            return path.is_file() and not path.is_symlink()
        except OSError as exc:
            raise BlobSecurityError("blob existence could not be checked safely") from exc

    def delete(self, storage_key: str) -> None:
        path = self._path_for_key(storage_key, create_parent=False)
        try:
            path.unlink()
        except FileNotFoundError as exc:
            raise BlobNotFound("blob does not exist") from exc
        except OSError as exc:
            raise BlobSecurityError("blob could not be deleted safely") from exc

    @staticmethod
    def _unlink_quietly(path: Path) -> None:
        try:
            path.unlink(missing_ok=True)
        except OSError:
            LOGGER.warning("blob temporary cleanup failed", extra={"cleanup_failed": True})


def _base32(value: bytes) -> str:
    import base64

    return base64.b32encode(value).decode("ascii").lower().rstrip("=")
